#!/usr/bin/env python3
"""Make extensions/notation/lua/notation/fonts/leland.lua: what the engraver
needs of the Leland font until the kernel embeds it (`daw.api.smufl`).

  python3 -I smufl.py <leland metadata.json> <verovio data dir> > leland.lua

The metadata is the font's SMuFL metadata (the @vexflow-fonts/leland 1.0.1
package carries Leland 0.77's). The outlines come from Verovio's data
directory, which keeps each glyph of the font as an SVG path in font units
(1000 to the em, y up). Only the glyphs the engraver uses are kept, with
their outlines turned into absolute commands in staff spaces, y down, from
the glyph's origin, so a frontend that cannot draw the font can draw them
as paths. Leland is under the SIL Open Font License (LICENSE.txt beside the
data file).
"""
import json
import os
import re
import sys

GLYPHS = """
noteheadBlack noteheadHalf noteheadWhole noteheadDoubleWhole noteheadXBlack
gClef fClef gClef8vb
accidentalFlat accidentalNatural accidentalSharp accidentalDoubleSharp accidentalDoubleFlat
accidentalParensLeft accidentalParensRight
flag8thUp flag8thDown flag16thUp flag16thDown flag32ndUp flag32ndDown flag64thUp flag64thDown
restDoubleWhole restWhole restHalf restQuarter rest8th rest16th rest32nd rest64th
augmentationDot
timeSig0 timeSig1 timeSig2 timeSig3 timeSig4 timeSig5 timeSig6 timeSig7 timeSig8 timeSig9 timeSigCommon
tuplet0 tuplet1 tuplet2 tuplet3 tuplet4 tuplet5 tuplet6 tuplet7 tuplet8 tuplet9
articStaccatoAbove articStaccatoBelow articAccentAbove articAccentBelow
articTenutoAbove articTenutoBelow articMarcatoAbove articMarcatoBelow
dynamicPiano dynamicMezzo dynamicForte dynamicPPP dynamicPP dynamicMP dynamicMF dynamicFF dynamicFFF
repeatDot wiggleArpeggiatoUp wiggleArpeggiatoUpArrow wiggleArpeggiatoDownArrow
brace bracketTop bracketBottom
""".split()

UNITS = 250.0  # font units to a staff space


def absolute(d):
    """SVG path data with relative commands as absolute M, L, C and Z."""
    tokens = re.findall(r"[MmLlHhVvCcSsZz]|-?\d*\.?\d+(?:e-?\d+)?", d)
    out, i, cmd = [], 0, None
    x = y = sx = sy = 0.0
    last_c2 = None
    def nums(n):
        nonlocal i
        vals = [float(t) for t in tokens[i:i + n]]
        i += n
        return vals
    while i < len(tokens):
        t = tokens[i]
        if re.match(r"[A-Za-z]", t):
            cmd = t
            i += 1
            if cmd in "Zz":
                out.append(("Z",))
                x, y = sx, sy
                last_c2 = None
                continue
        rel = cmd.islower()
        c = cmd.upper()
        if c == "M":
            dx, dy = nums(2)
            x, y = (x + dx, y + dy) if rel else (dx, dy)
            sx, sy = x, y
            out.append(("M", x, y))
            cmd = "l" if rel else "L"
            last_c2 = None
        elif c == "L":
            dx, dy = nums(2)
            x, y = (x + dx, y + dy) if rel else (dx, dy)
            out.append(("L", x, y))
            last_c2 = None
        elif c == "H":
            (v,) = nums(1)
            x = x + v if rel else v
            out.append(("L", x, y))
            last_c2 = None
        elif c == "V":
            (v,) = nums(1)
            y = y + v if rel else v
            out.append(("L", x, y))
            last_c2 = None
        elif c == "C":
            a = nums(6)
            if rel:
                a = [a[0] + x, a[1] + y, a[2] + x, a[3] + y, a[4] + x, a[5] + y]
            out.append(("C", *a))
            last_c2 = (a[2], a[3])
            x, y = a[4], a[5]
        elif c == "S":
            a = nums(4)
            if rel:
                a = [a[0] + x, a[1] + y, a[2] + x, a[3] + y]
            c1 = (2 * x - last_c2[0], 2 * y - last_c2[1]) if last_c2 else (x, y)
            out.append(("C", c1[0], c1[1], *a))
            last_c2 = (a[0], a[1])
            x, y = a[2], a[3]
    return out


def lua_number(v):
    s = "%.3f" % v
    s = s.rstrip("0").rstrip(".")
    return "0" if s in ("-0", "") else s


def main():
    meta = json.load(open(sys.argv[1]))
    data = sys.argv[2]
    xml = open(os.path.join(data, "Leland.xml")).read()
    codes = {m.group(2): m.group(1) for m in re.finditer(r'<g c="([0-9A-F]+)"[^>]* n="([^"]+)"', xml)}
    lines = [
        "-- Generated by extensions/notation/tools/smufl.py from Leland %s (SIL Open" % meta["fontVersion"],
        "-- Font License, LICENSE.txt beside this file): its engraving defaults, and",
        "-- for the glyphs the engraver uses their code point, bounding box and",
        "-- anchors (staff spaces, y up, as SMuFL gives them) and outline (staff",
        "-- spaces from the glyph's origin, y down). Do not edit by hand.",
        "return {",
        '  name = "Leland", version = "%s",' % meta["fontVersion"],
        "  defaults = {",
    ]
    for k, v in sorted(meta["engravingDefaults"].items()):
        if isinstance(v, (int, float)):
            lines.append("    %s = %s," % (k, lua_number(v)))
    lines.append("  },")
    lines.append("  glyphs = {")
    for name in GLYPHS:
        cp = codes[name]
        bb = meta["glyphBBoxes"][name]
        parts = ["cp = 0x%s" % cp, "bbox = { %s }" % ", ".join(lua_number(v) for v in bb["bBoxSW"] + bb["bBoxNE"])]
        anchors = meta["glyphsWithAnchors"].get(name)
        if anchors:
            parts.append("anchors = { %s }" % ", ".join(
                "%s = { %s, %s }" % (k, lua_number(v[0]), lua_number(v[1])) for k, v in sorted(anchors.items())))
        svg = open(os.path.join(data, "Leland", cp + ".xml")).read()
        d = re.search(r' d="([^"]+)"', svg).group(1)
        path = []
        for seg in absolute(d):
            path.append('"%s"' % seg[0])
            for k in range(1, len(seg), 2):
                path.append(lua_number(seg[k] / UNITS))
                path.append(lua_number(-seg[k + 1] / UNITS))
        parts.append("path = { %s }" % ", ".join(path))
        lines.append("    %s = { %s }," % (name, ", ".join(parts)))
    lines.append("  },")
    lines.append("}")
    print("\n".join(lines))


main()
