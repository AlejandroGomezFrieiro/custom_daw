-- Recording, mixing, the master, sends, rendering and the engine, driven
-- with the real keys and commands. Loaded by tests/suite.lua with its helpers.
local T = ...
local test, eq, fresh = T.test, T.eq, T.fresh
local api = paw.api

local function keys(text)
  paw.keymap.feed(text)
  api.undo_checkpoint()
end

local function start()
  fresh()
  paw.keymap.feed("<Esc><Esc>")
  while paw.ui.float do paw.ui.close() end
  paw.ui.focus("arrange")
end

--- The last message paw gave.
local function said()
  local m = paw.ui.messages[#paw.ui.messages]
  return m and m.text or ""
end

local function screen(w, h) return table.concat(api.ui_snapshot(w or 120, h or 30), "\n") end

test("the cursor reaches the master: j after the last track, $ and l in the mixer, /master", function()
  start()
  local a, b = paw.add_track({ name = "Drums" }), paw.add_track({ name = "Bass" })
  paw.cursor.set_track(a)
  keys("G")
  eq(paw.cursor.track_id(), b.id, "G goes to the last track")
  keys("j")
  eq(paw.cursor.track_id(), 0, "j from the last track goes to the master")
  eq(paw.cursor.on_master(), true, "the cursor is on the master")
  keys("j")
  eq(paw.cursor.track_id(), 0, "and stays there")
  keys("aLimiter<CR>")
  eq(paw.master:devices()[1] and paw.master:devices()[1].kind, "limiter", "a adds a device to the master")
  keys("3-")
  eq(paw.master.volume, -3, "- lowers the master's fader")
  keys(":clip.add length=4<CR>")
  eq(#paw.master:clips(), 0, "the master takes no clips")
  eq(said():find("master track has no clips") ~= nil, true, "and says so: " .. said())
  keys("dd")
  eq(#paw.tracks(), 2, "dd does not remove the master")
  eq(said():find("master") ~= nil, true, "and says why: " .. said())
  keys("k")
  eq(paw.cursor.track_id(), b.id, "k from the master goes back to the last track")
  keys("gg/mast<CR>")
  eq(paw.cursor.track_id(), 0, "/ finds the master by name")
  keys("k")
  -- With a count, j stops on the master too; an operator keeps to the tracks.
  keys("gg5j")
  eq(paw.cursor.track_id(), 0, "5j goes no further than the master")
  keys("ggVj")
  eq(paw.keymap.selection().r1, 2, "a selection keeps to the tracks")
  keys("<Esc>")

  -- In the mixer the master is the last strip.
  paw.cursor.set_track(a)
  keys(",m")
  eq(paw.ui.focused, "mixer", ",m shows the mixer")
  keys("$")
  eq(paw.cursor.track_id(), 0, "$ goes to the master's strip")
  keys("h")
  eq(paw.cursor.track_id(), b.id, "h goes back to the last track's")
  keys("l")
  eq(paw.cursor.track_id(), 0, "l from the last strip goes to the master's")
  keys("+")
  eq(paw.master.volume, -2, "+ raises the master's fader")
  eq(screen():find("volume %-2") ~= nil, true, "the title bar names the master's fader")
  keys("0/master<CR>")
  eq(paw.cursor.track_id(), 0, "/ finds the master's strip")
  keys("0V$")
  local sel = paw.keymap.selection()
  eq(sel.r0 .. "-" .. sel.r1, "1-2", "V$ selects the tracks' strips, not the master's")
  keys("<Esc>")
end)

test("R records from the cursor, as Shift-Enter plays from it", function()
  start()
  api.engine_restart({ backend = "null", test_input = { frequency = 440, level = -12, channels = 2 }, test_midi = { "Keys A" } })
  T.after(function() api.engine_restart({ backend = "null" }) end)
  T.after(function() paw.opt.count_in = 0 end)
  paw.opt.count_in = 0
  paw.project.save(T.scratch .. "/rfromcursor.json")
  local gtr = paw.add_track({ name = "Guitar" })
  paw.cursor.set_track(gtr)
  keys("Isignal 1<CR>")
  keys("r")
  paw.transport.seek(0)
  keys("3|")
  eq(paw.cursor.beat, 8, "3| puts the cursor at bar 3")
  keys("R")
  local deadline = api.now() + 3000
  while not (paw.transport.recording and paw.transport.playing) and api.now() < deadline do api.sleep(10) end
  api.sleep(300)
  keys("<Space>")
  paw.flush()
  local clips = gtr:clips()
  eq(#clips, 1, "the take is a clip")
  eq(math.abs(clips[1].start - 8) < 0.01, true, "it starts at the cursor, not at the playhead (" .. clips[1].start .. ")")
end)

test("the fader: - on a track above +6 dB goes down a dB, not to +6", function()
  start()
  local t = paw.add_track({ name = "Loud" })
  paw.cursor.set_track(t)
  keys("grv=12<CR>")
  eq(t.volume, 12, "grv types a level above the fader's travel")
  keys("-")
  eq(t.volume, 11, "- in the arrange view goes down one dB")
  keys("+")
  eq(t.volume, 11, "+ does not raise it, above the fader's travel")
  keys(",m-")
  eq(t.volume, 10, "- in the mixer goes down one dB")
  keys("<Esc>")
  t.volume = 5
  keys("3+")
  eq(t.volume, 6, "+ stops at the top of the travel, +6 dB")
  keys("grv=30<CR>")
  eq(t.volume, 24, "a typed level stops at the engine's limit, +24 dB")
end)

test(":send to a track that has the send sets its level, or says it is unchanged; :send acts on a selection", function()
  start()
  local a, b, c = paw.add_track({ name = "Vox" }), paw.add_track({ name = "Gtr" }), paw.add_track({ name = "Reverb" })
  paw.cursor.set_track(a)
  keys(":send Reverb -9<CR>")
  eq(a.sends[1].level, -9, ":send adds the send")
  keys(":send Reverb<CR>")
  eq(a.sends[1].level, -9, ":send again with no level leaves it")
  eq(said(), "Vox already sends to Reverb at -9 dB: unchanged", "and says so")
  keys(":send Reverb -4<CR>")
  eq(#a.sends .. " " .. a.sends[1].level, "1 -4", ":send with a level sets the send's level")
  eq(said(), "Vox ↗ Reverb now at -4 dB (was -9)", "and says what it was")
  -- A selection of tracks: each one sends.
  keys("ggVj:send Reverb -12<CR>")
  eq(a.sends[1].level .. " " .. b.sends[1].level, "-12 -12", ":send on a selection acts on each track")
  eq(said():find("^2 tracks") ~= nil, true, "and names each: " .. said())
  keys("<Esc>,m0Vl:send Reverb -3<CR>")
  eq(a.sends[1].level .. " " .. b.sends[1].level, "-3 -3", "on a selection of strips in the mixer too")
  keys("<Esc>")
  eq(#c.sends, 0, "the return sends nowhere")
end)

test(":loudness shows the master's device panel, with the meter it added", function()
  start()
  local synth = T.tone("Synth", 4)
  paw.cursor.set_track(synth)
  keys(":loudness<CR>")
  eq(paw.cursor.track_id(), 0, "the cursor goes to the master")
  local meter = paw.master:device("meter")
  eq(meter ~= nil, true, "a meter on the master")
  local device = paw.ui.views.devices:selected()
  eq(device and device.id, meter.id, "the device panel shows the master's meter")
  eq(screen():find("Master") ~= nil, true, "and names the master")
  paw.ui.close()
end)

test(":render expands ~ as :import and :export do", function()
  start()
  local render = require("paw.render")
  local real, got = render.render, nil
  T.after(function() render.render = real end)
  render.render = function(path) got = path return { peak = 0, length = 0, path = path, sample_rate = 48000 } end
  keys(":render ~/paw-mix.wav<CR>")
  render.render = real
  eq(got, os.getenv("HOME") .. "/paw-mix.wav", ":render ~/ names a file in the home folder")
  eq(paw.util.expand_path("~"), os.getenv("HOME"), "~ alone is the home folder")
  eq(paw.util.expand_path("~x/a.wav"), "~x/a.wav", "~ before a name stays as it is")
  eq(paw.util.expand_path("a/~/b"), "a/~/b", "and ~ after the start")
end)

test("K on a MIDI track with no instrument says it has none, and how to add one", function()
  start()
  local t = paw.add_track({ name = "Keys" })
  t:add_clip({ start = 0, length = 4, notes = { { pitch = "C4", start = 0, length = 1 } } })
  paw.cursor.set_track(t)
  keys("K")
  local text = screen()
  paw.ui.close()
  eq(text:find("no instrument", 1, true) ~= nil, true, "K says the track has no instrument")
  eq(text:find("Press `a`", 1, true) ~= nil, true, "and how to add one")
  t:add_device("synth")
  keys("K")
  text = screen()
  paw.ui.close()
  eq(text:find("no instrument", 1, true), nil, "with a synth it says nothing of the kind")
end)

test(":engine threads=2 reports the new count", function()
  start()
  local before = paw.opt.threads
  T.after(function() paw.opt.threads = before end)
  keys(":engine threads=1<CR>")
  eq(said():find("1 thread,", 1, true) ~= nil, true, "one thread: " .. said())
  keys(":engine threads=2<CR>")
  eq(said():find("2 threads", 1, true) ~= nil, true, "two threads: " .. said())
  keys(":engine threads=many<CR>")
  eq(said():find("a number", 1, true) ~= nil, true, "a word that is no number is refused: " .. said())
end)
